// Frame-cost instrument for the campo skin: deterministic, headless, offline.
//
// The handoff of 2026-07-30 left the links drawn "always, faint, by weight"
// with the neighbour index built once, and pinned the defect class (all pairs
// every frame) by static tests -- but the actual per-frame COST of the
// published skin had never been executed and counted. "NOT measured: fps on a
// phone" stays true: a phone cannot be measured from CI. What CAN be measured
// deterministically is the WORK per frame -- drawn segments, canvas geometry
// ops, neighbour-index size -- because counts do not depend on the machine.
// Milliseconds are reported as informative context only, never pinned.
//
// Technique: same as tools/iskvw_piel_smoke.mjs -- the PUBLISHED file's own
// inline script runs in node inside a vm with DOM stubs; nothing in the skin
// is modified. The 2d context is a counting proxy: every stroke() is one drawn
// segment (the link loops do beginPath/moveTo/lineTo/stroke per link), every
// arc/gradient/fillText is node-drawing work. Scenarios are REAL: the repo's
// campo.json (today's live fallback, 219 works) and the publish-time
// archivo.json substrate (--archivo, generated by gen_archivo_iskvw.py exactly
// as .github/workflows/publicar_iskvw.yml does), entered through the skin's
// own seed model `#semilla=&centro=&escala=` plus the pinch aperture.
//
// Usage:
//   node tools/iskvw_piel_medir.mjs [--archivo path/to/archivo.json]
//                                   [--frames N] [--json]
// Prints a table and, as the LAST line, one machine-readable JSON object.
// Invoked by tests/test_iskvw_piel_medir.py, which pins the counts.
