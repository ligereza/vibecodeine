const noop = () => {};

// One fresh sandbox per scenario: the skin keeps its state in module-level
// globals (E, NODOS, VECINOS...), so reusing a context would leak one
// scenario's state into the next and the ordering would stop being neutral.
function arrancarPiel({ substrate, hash }) {
  // Canvas op counters. stroke() is the segment count: both link loops in the
  // skin emit exactly one stroke per drawn segment. lineTo is kept as a
  // cross-check (it must equal stroke for pure segment drawing).
  const cnt = { segmentos: 0, lineas: 0, arcos: 0, gradientes: 0, textos: 0 };
  const resetCnt = () => { for (const k of Object.keys(cnt)) cnt[k] = 0; };

  const ctx2d = new Proxy({}, {
    get: (t, k) => {
      if (k === "canvas") return canvas;
      if (k === "createRadialGradient" || k === "createLinearGradient")
        return () => { cnt.gradientes++; return { addColorStop: noop }; };
      if (k === "fillText") return () => { cnt.textos++; };
      if (k === "measureText") return () => ({ width: 10 });
      if (k === "getImageData") return () => ({ data: new Uint8ClampedArray(4) });
      if (k === "arc") return () => { cnt.arcos++; };
      if (k === "lineTo") return () => { cnt.lineas++; };
      if (k === "stroke") return () => { cnt.segmentos++; };
      return noop;
    },
    set: () => true,
  });
  // Stubs compartidos con la sonda (tools/lib/piel_dom.mjs): cada herramienta
  // tenia su copia y las dos tenian la forma de `campo`, que es como dos de
  // tres pieles quedaron sin medicion. Un arreglo duplicado es el mismo defecto
  // que un padron de proveedores escrito a mano dos veces.
  const canvas = elementoGenerico(ctx2d);
  const el = () => elementoGenerico(ctx2d);
  const doc = documentoStub(ctx2d, canvas);
  const getEl = doc.getElementById;

  let rafQueue = [];
  const sandbox = {
    console, Math, JSON, Date, performance,
    URLSearchParams,                   // the seed model parses the hash with it
    requestAnimationFrame: cb => { rafQueue.push(cb); return rafQueue.length; },
    cancelAnimationFrame: noop,
    setTimeout: () => 0, clearTimeout: noop, setInterval: () => 0, clearInterval: noop,
    // The fetch stub decides WHICH substrate this scenario measures:
    // "archivo" serves the generated archivo.json (pieces + links, the
    // publish-time path); "campo" 404s it so the skin degrades to the
    // repo's campo.json exactly like today's live site does without it.
    fetch: async (url) => {
      const u = String(url);
      if (/datos\/archivo\.json$/.test(u)) {
        if (substrate === "archivo" && archivoPath) {
          try {
            const txt = readFileSync(archivoPath, "utf8");
            return { ok: true, json: async () => JSON.parse(txt) };
          } catch { return { ok: false, json: async () => ({}) }; }
        }
        return { ok: false, json: async () => ({}) };
      }
      // Cualquier ruta relativa a la piel, no solo `datos/*.json` por nombre.
      // Servir unicamente los archivos que UNA piel pide no es una medicion.
      const partes = resolverPedido(u, PIEL);
      if (partes) {
        try {
          const txt = readFileSync(join(raiz, ...partes), "utf8");
          return { ok: true, json: async () => JSON.parse(txt),
                   text: async () => txt };
        } catch { /* cae al 404 de abajo */ }
      }
      return { ok: false, json: async () => ({}), text: async () => "" };
    },
    addEventListener: noop, removeEventListener: noop, history: { replaceState: noop },
    location: { hash, href: "http://medir.local/" },
    navigator: { maxTouchPoints: 0 },
    devicePixelRatio: 1, innerWidth: 800, innerHeight: 600,
  };
  sandbox.window = sandbox;
  sandbox.document = doc;

  const context = vm.createContext(sandbox);
  let failed = null;
  const onRejection = (e) => { failed = failed || e; };
  process.on("unhandledRejection", onRejection);
  try {
    for (const src of scripts) vm.runInContext(src, context, { timeout: 10000 });
  } catch (e) { failed = e; }

  return {
    context, cnt, resetCnt,
    fallo: () => failed,
    cerrar: () => process.removeListener("unhandledRejection", onRejection),
    tomarFrames: () => { const b = rafQueue; rafQueue = []; return b; },
  };
}

const espera = ms => new Promise(r => setTimeout(r, ms));

async function medirEscenario(substrate, nombre, hash, pinch) {
  const piel = arrancarPiel({ substrate, hash });
  await espera(25);                    // arrancar() is async: drain the loader
  if (piel.fallo()) throw piel.fallo();

  // Freeze the gesture so the frame is the FIELD frame, pure: no velocity, no
  // resolution (tocando=true keeps resolver() out), aperture set by pinch --
  // the same variable the real pinch gesture writes, so diafragma() sees a
  // state a visitor can actually produce.
  vm.runInContext(
    `E.vel = 0; E.suave = 0; E.tocando = true; E.pinch = ${pinch};`,
    piel.context);

  const tiempos = [], porFrame = [];
  for (let i = 0; i < warmup + frames; i++) {
    piel.resetCnt();
    const lote = piel.tomarFrames();
    if (!lote.length) throw new Error(`no frame queued at step ${i} (${nombre})`);
    const t0 = performance.now();
    for (const cb of lote) cb(t0);
    const dt = performance.now() - t0;
    if (piel.fallo()) throw piel.fallo();
    if (i >= warmup) { tiempos.push(dt); porFrame.push({ ...piel.cnt }); }
  }

  // Determinism is the contract: with the gesture frozen, every measured frame
  // must do identical work. Random jitter moves pixels, never counts.
  const primero = JSON.stringify(porFrame[0]);
  for (const f of porFrame) {
    if (JSON.stringify(f) !== primero)
      throw new Error(`unstable counts in ${nombre}: ${primero} vs ${JSON.stringify(f)}`);
  }

  const estado = JSON.parse(vm.runInContext(`JSON.stringify({
    nodos: NODOS.length,
    largo: Math.round(LARGO),
    indice_entradas: VECINOS.reduce((a, l) => a + l.length, 0),
    vinculos_indexados: VECINOS.reduce((a, l) => a + l.length, 0) / 4,
    pos: Math.round(E.pos),
  })`, piel.context));
  piel.cerrar();

  tiempos.sort((a, b) => a - b);
  return {
    sustrato: substrate, escenario: nombre, hash, pinch,
    ...estado, ...porFrame[0],
    // n*(n-1)/2: what the all-against-all defect would cost on this substrate.
    todos_los_pares: estado.nodos * (estado.nodos - 1) / 2,
    ms_mediana: Number(tiempos[Math.floor(tiempos.length / 2)].toFixed(3)),
  };
}

// Probe boot: read the field the skin actually built (ids, ys, LARGO) so the
// scenario grid is derived from the REAL data, not from a copy of its math.
async function sondear(substrate) {
  const piel = arrancarPiel({ substrate, hash: "" });
  await espera(25);
  if (piel.fallo()) throw piel.fallo();
  piel.tomarFrames();                  // discard: the probe draws nothing
  const campo = JSON.parse(vm.runInContext(`JSON.stringify({
    ids: NODOS.map(n => n.obra.id),
    ys: NODOS.map(n => Math.round(n.y)),
    largo: Math.round(LARGO),
  })`, piel.context));
  piel.cerrar();
  return campo;
}

// Densest reading position: the y that puts the most nodes inside the OPEN
// diaphragm band (alcance = 260 + 1*1500, from diafragma() at s=1). This is
// the worst case the ceiling test guards.
function centroDenso(ys) {
  const ALCANCE_ABIERTO = 1760;
  const orden = [...ys].sort((a, b) => a - b);
  let mejor = orden[0] || 0, mejorN = -1;
  for (const c of orden) {
    const n = orden.filter(y => Math.abs(y - c) <= ALCANCE_ABIERTO).length;
    if (n > mejorN) { mejorN = n; mejor = c; }   // ties: lowest y, deterministic
  }
  return { centro: mejor, en_banda: mejorN };
}

