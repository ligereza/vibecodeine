const filas = [];
for (const s of substratos) {
  const campo = await sondear(s);
  if (!campo.ids.length) { console.error(`empty field for substrate ${s}`); process.exit(1); }
  const denso = centroDenso(campo.ys);
  const primera = campo.ids[0];
  const medio = Math.round(campo.largo / 2);
  // The grid: entry seed as shipped, then centers across the field, closed and
  // open apertures, the densest band (worst case), and one lateral scale.
  const grilla = [
    ["entrada cerrada",  `#semilla=${primera}`, 0],
    ["entrada abierta",  `#semilla=${primera}`, 1],
    ["medio abierto",    `#centro=${medio}`, 1],
    ["denso cerrado",    `#centro=${denso.centro}`, 0],
    ["denso medio",      `#centro=${denso.centro}`, 0.5],
    ["denso abierto",    `#centro=${denso.centro}`, 1],
    ["denso escalado",   `#centro=${denso.centro}&escala=0.8`, 1],
  ];
  for (const [nombre, hash, pinch] of grilla)
    filas.push(await medirEscenario(s, nombre, hash, pinch));
}

